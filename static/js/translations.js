// Função para traduzir textos dinâmicos comuns
function translateDynamicText(text) {
    if (!text || !translator) return text;
    
    const currentLang = translator.getCurrentLanguage();
    const translations = {
        'Gratuito': currentLang === 'en' ? 'Free' : 'Gratuito',
        'Não informado': currentLang === 'en' ? 'Not informed' : 'Não informado',
        'Não informado.': currentLang === 'en' ? 'Not informed.' : 'Não informado.',
        'avaliações': currentLang === 'en' ? 'reviews' : 'avaliações',
        'avaliação': currentLang === 'en' ? 'review' : 'avaliação'
    };
    
    return translations[text] || text;
}

